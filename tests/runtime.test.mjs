import test from 'node:test';
import assert from 'node:assert/strict';
import {CASES} from '../src/content.js';
import {STRATEGIES,SCENES} from '../src/adventure.js';
test('fluxo integral da aventura: cenário, guia, evidências, simulação e debriefing',async()=>{
 const handlers={};const stored=new Map();const root={innerHTML:'',addEventListener:(type,cb)=>{handlers[type]=cb;}};
 const doc={getElementById:id=>id==='app'?root:null,querySelector:()=>null};
 Object.defineProperty(globalThis,'document',{value:doc,configurable:true});
 Object.defineProperty(globalThis,'window',{value:{addEventListener:()=>{},scrollTo:()=>{}},configurable:true});
 Object.defineProperty(globalThis,'localStorage',{value:{getItem:key=>stored.get(key)||null,setItem:(key,value)=>stored.set(key,value)},configurable:true});
 Object.defineProperty(globalThis,'location',{value:{protocol:'http:',hostname:'example.org'},configurable:true});
 Object.defineProperty(globalThis,'navigator',{value:{},configurable:true});
 stored.set('immunoverse.doctor.v1',JSON.stringify({version:1,name:'Aluno Teste'}));
 await import('../src/app.js?runtime-test');
 const click=dataset=>{const el={dataset,closest:()=>el};handlers.click({target:el});};
 assert.match(root.innerHTML,/Trilha semestral/);click({page:'home'});assert.match(root.innerHTML,/42<\/b> missões clínicas/);
 click({page:'expedition'});assert.match(root.innerHTML,/Mapa vivo/);
 for(const s of SCENES)assert.ok(root.innerHTML.includes(`data-scene-open="${s.id}"`));
 click({sceneOpen:'mucosa'});click({hotspot:'1'});assert.match(root.innerHTML,/IgA secretora/);
 click({page:'heroes'});assert.match(root.innerHTML,/Células e mecanismos/);click({atlasCell:'dendritic'});
 assert.match(root.innerHTML,/Célula dendrítica/);
 click({page:'home'});click({world:'hepatites'});
 click({case:'hep-09'});assert.match(root.innerHTML,/Descubra o mecanismo oculto/);
 const c=CASES.find(c=>c.id==='hep-09');
 click({action:'next'});
 assert.match(root.innerHTML,/Laboratório de conexões/);
 for(const e of c.evidence){click({evidence:e.id});click({mechanism:e.mechanism});}
 assert.match(root.innerHTML,/Três relações corretamente estabelecidas/);
 click({action:'next'});
 for(let i=0;i<4;i++)click({step:String(i)});
 assert.match(root.innerHTML,/Sequência concluída/);
 click({action:'next'});
 click({answer:`decision:${c.decision.options.findIndex(o=>o.correct)}`});click({action:'next'});
 assert.match(root.innerHTML,/Defina sua estratégia/);assert.match(root.innerHTML,/sim-invader/);
 click({answer:`strategy:${STRATEGIES[c.world].options.findIndex(o=>o.correct)}`});click({action:'next'});
 assert.match(root.innerHTML,/Transfira o conhecimento/);
 click({answer:`transfer:${c.transfer.options.findIndex(o=>o.correct)}`});click({action:'next'});
 assert.match(root.innerHTML,/Missão concluída!/);assert.match(root.innerHTML,/100/);
 const progress=JSON.parse(stored.get('immunoverse.play.v2'));
 assert.equal(progress.companion,'Maco');
 assert.equal(progress.records['hep-09'].score,100);
 assert.equal(progress.session.phase,'debrief');
});
